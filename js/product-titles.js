// Function to get product title by handle or product name
// Improved matching: handles both old format (ll-XXXX) and new format (luna-luce-italia-ll-XXXX)
function getProductTitle(productName) {
    if (!productName) return null;
    
    // Normalize product name
    const normalized = productName.toLowerCase().replace(/\s+/g, '-');
    
    // Try exact match first
    if (productTitles[normalized]) {
        return productTitles[normalized];
    }
    
    // Try with "luna-luce-italia-" prefix (new format)
    const withPrefix = 'luna-luce-italia-' + normalized;
    if (productTitles[withPrefix]) {
        return productTitles[withPrefix];
    }
    
    // Extract product code pattern from product name
    // Examples: "ll-310-1" -> "310-1", "ll-310-2-r" -> "310-2", "ll-2007" -> "2007"
    const fullCodeMatch = normalized.match(/ll-?(\d+(?:-\d+)?(?:-[a-z]+)?)/);
    if (fullCodeMatch) {
        const fullCode = fullCodeMatch[1]; // e.g., "310-1", "310-2", "2007"
        
        // Priority 1: Try to find handle with "luna-luce-italia-ll-" + fullCode
        const newFormatPattern = 'luna-luce-italia-ll-' + fullCode;
        for (const [key, value] of Object.entries(productTitles)) {
            if (key.startsWith(newFormatPattern + '-') || key === newFormatPattern) {
                return value;
            }
        }
        
        // Priority 2: Try old format "ll-" + fullCode
        const oldFormatPattern = 'll-' + fullCode;
        for (const [key, value] of Object.entries(productTitles)) {
            if (key.startsWith(oldFormatPattern + '-') || key === oldFormatPattern) {
                return value;
            }
        }
        
        // Priority 3: Handle contains the full code pattern with variant matching
        const codeParts = fullCode.split('-');
        if (codeParts.length >= 2) {
            const baseCode = codeParts[0];
            const variant = codeParts[1];
            
            // Search for handles containing "ll-310-1" pattern (new format)
            const searchPatternNew = 'luna-luce-italia-ll-' + baseCode + '-' + variant;
            for (const [key, value] of Object.entries(productTitles)) {
                if (key.startsWith(searchPatternNew) || 
                    key.includes('-ll-' + baseCode + '-' + variant + '-') ||
                    key === searchPatternNew) {
                    return value;
                }
            }
            
            // Search for handles containing "ll-310-1" pattern (old format)
            const searchPatternOld = 'll-' + baseCode + '-' + variant;
            for (const [key, value] of Object.entries(productTitles)) {
                if (key.startsWith(searchPatternOld) || 
                    key.includes('-' + baseCode + '-' + variant + '-') ||
                    key === searchPatternOld) {
                    return value;
                }
            }
            
            // Check for variant suffixes in product name (e.g., "SQ", "R", "S")
            const variantSuffixMatch = normalized.match(/ll-?\d+-\d+-([a-z]+)/);
            if (variantSuffixMatch) {
                const variantSuffix = variantSuffixMatch[1];
                // Search for handles with this variant suffix (new format)
                for (const [key, value] of Object.entries(productTitles)) {
                    if (key.includes('ll-' + baseCode + '-' + variant) && key.includes(variantSuffix)) {
                        return value;
                    }
                }
            }
        }
        
        // Priority 4: Try base code only, but ONLY if no variant was specified
        if (codeParts.length === 1) {
            const baseCode = codeParts[0];
            let bestMatch = null;
            let bestMatchKey = null;
            
            // Try new format first
            for (const [key, value] of Object.entries(productTitles)) {
                if (key.includes('ll-' + baseCode + '-') || key.includes('-ll-' + baseCode + '-')) {
                    if (!bestMatch || key.length < bestMatchKey.length) {
                        bestMatch = value;
                        bestMatchKey = key;
                    }
                }
            }
            if (bestMatch) {
                return bestMatch;
            }
        }
    }
    
    // Try partial match - search for handles that contain parts of the product name
    const nameParts = normalized.split('-');
    if (nameParts.length >= 2) {
        // Try "ll-XXXX" pattern
        const searchKey = nameParts[0] + '-' + nameParts[1]; // e.g., "ll-310"
        // Try new format
        for (const [key, value] of Object.entries(productTitles)) {
            if (key.includes('luna-luce-italia-' + searchKey) || key.startsWith(searchKey)) {
                return value;
            }
        }
    }
    
    return null;
}

